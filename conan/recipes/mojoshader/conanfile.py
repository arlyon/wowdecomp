import os

from conan import ConanFile
from conan.tools.files import copy, save
from conan.tools.scm import Git

# Reviewed revision pinned by cmake/MojoShader.cmake. Keep the two in sync.
REVISION = "ad5dff84830c2863c841f4b1f4e3df78c705b383"


class MojoShaderConan(ConanFile):
    name = "mojoshader"
    version = "0.0.0-ad5dff8"
    description = ("MojoShader source checkout pinned for wowdecomp's shader frontend "
                   "(consumed as a source directory, not as a linked library)")
    settings = "os", "arch", "compiler", "build_type"

    def source(self):
        # Clone the reviewed revision. The project verifies `git rev-parse HEAD`,
        # so the checkout (including its .git directory) is what we ship.
        git = Git(self, folder=os.path.join(self.source_folder, "checkout"))
        git.clone(url="https://github.com/icculus/mojoshader.git", target=".")
        git.checkout(REVISION)

    def package(self):
        src = os.path.join(self.source_folder, "checkout")
        copy(self, "*", src=src, dst=os.path.join(self.package_folder, "source"))
        # mojoshader.h includes this unless MOJOSHADER_NO_VERSION_INCLUDE is set.
        # wowdecomp sets that for its own build, but generate it anyway so the
        # checkout is complete for other consumers.
        save(self, os.path.join(self.package_folder, "source", "mojoshader_version.h"),
             "/* Generated by wowdecomp's conan recipe. */\n"
             "#ifndef _INCL_MOJOSHADER_VERSION_H_\n"
             "#define _INCL_MOJOSHADER_VERSION_H_\n"
             "#define MOJOSHADER_VERSION 0\n"
             "#define MOJOSHADER_CHANGESET \"conan\"\n"
             "#endif\n")

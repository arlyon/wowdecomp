import os

from conan import ConanFile
from conan.tools.files import save


class WowDecompDeps(ConanFile):
    """Dependency umbrella for the client build.

    wowdecomp consumes its two pinned dependencies as *source directories* and a
    compiler binary, not as linked CMake packages, so instead of CMakeDeps we
    generate a small snippet that CMakePresets.json injects via
    CMAKE_PROJECT_INCLUDE (see the `vulkan-client-conan` preset).
    """

    name = "wowdecomp-deps"
    version = "0.0.0"
    settings = "os", "arch", "compiler", "build_type"
    requires = (
        "mojoshader/0.0.0-ad5dff8",
        "slang/2026.4.2",
    )

    def generate(self):
        mojoshader = self.dependencies["mojoshader"].package_folder
        slang = self.dependencies["slang"].package_folder
        slangc = os.path.join(slang, "bin", "slangc")

        content = "\n".join([
            "# Generated by Conan (conanfile.py::generate). Do not edit by hand.",
            "# Injected into the client build via CMAKE_PROJECT_INCLUDE.",
            f'set(WOWDECOMP_MOJOSHADER_SOURCE "{mojoshader}/source" CACHE PATH "" FORCE)',
            f'set(WOWDECOMP_SLANG_SOURCE "{slang}/source" CACHE PATH "" FORCE)',
            f'set(WOWDECOMP_SLANGC "{slangc}" CACHE FILEPATH "" FORCE)',
            "",
        ])
        save(self, os.path.join(self.generators_folder, "deps.cmake"), content)
